#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ASN_LIST="${CN_HOME_BROADBAND_ASNS_FILE:-${ROOT}/data/carriers/home-broadband-asns.tsv}"
OUTPUT="${CN_HOME_BROADBAND_FILE:-${ROOT}/data/carriers/home-broadband.txt}"
ASN_BASE_URL="${CN_ASN_BASE_URL:-https://raw.githubusercontent.com/ipverse/as-ip-blocks/master/as}"
# BGP-derived per-carrier lists covering every ASN registered to each carrier,
# including provincial ASNs that the curated list above does not enumerate.
OPERATOR_BASE_URL="${CN_OPERATOR_BASE_URL:-https://raw.githubusercontent.com/gaoyifan/china-operator-ip/ip-lists}"
OPERATOR_LISTS="${CN_HOME_BROADBAND_OPERATORS:-chinanet unicom cmcc}"
# Premium/international networks kept out of the operator lists (see home-broadband-asns.tsv).
EXCLUDED_ASNS="${CN_HOME_BROADBAND_EXCLUDED_ASNS:-AS4809 AS9929 AS58453}"
MERGE_TOOL="${ROOT}/tools/cidr_merge.py"
WORK_DIR=""

cleanup() {
  [[ -n "${WORK_DIR:-}" ]] && rm -rf "${WORK_DIR}"
}
trap cleanup EXIT

if [[ ! -r "${ASN_LIST}" ]]; then
  echo "Missing home broadband ASN list: ${ASN_LIST}" >&2
  exit 1
fi
if ! command -v curl >/dev/null 2>&1; then
  echo "curl is required to refresh home broadband data." >&2
  exit 1
fi

WORK_DIR="$(mktemp -d)"
RAW_FILE="${WORK_DIR}/raw.txt"
OPERATOR_FILE="${WORK_DIR}/operators.txt"
EXCLUDED_FILE="${WORK_DIR}/excluded.txt"
SORTED_FILE="${WORK_DIR}/sorted.txt"
: > "${RAW_FILE}"
: > "${OPERATOR_FILE}"
: > "${EXCLUDED_FILE}"

fetch_ipv4_prefixes() {
  local url="$1"
  local target="$2"
  local body
  body="$(curl -fsSL --connect-timeout 20 --retry 2 --retry-delay 1 "${url}")" || {
    echo "Failed to download ${url}" >&2
    return 1
  }
  body="$(awk 'NF && $0 !~ /^#/ && $0 ~ /^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+\/[0-9]+$/ {print $0}' <<<"${body}")"
  if [[ -z "${body}" ]]; then
    echo "No IPv4 prefixes in ${url}" >&2
    return 1
  fi
  printf '%s\n' "${body}" >> "${target}"
}

while IFS=$'\t' read -r raw_asn _carrier _description; do
  [[ "${raw_asn}" =~ ^AS[0-9]+$ ]] || continue
  asn="${raw_asn#AS}"
  url="${ASN_BASE_URL%/}/${asn}/ipv4-aggregated.txt"
  echo "[home-broadband] ${raw_asn} ${url}" >&2
  fetch_ipv4_prefixes "${url}" "${RAW_FILE}"
done < "${ASN_LIST}"

if [[ ! -s "${RAW_FILE}" ]]; then
  echo "No home broadband IPv4 prefixes were downloaded." >&2
  exit 1
fi

for operator in ${OPERATOR_LISTS}; do
  url="${OPERATOR_BASE_URL%/}/${operator}.txt"
  echo "[home-broadband] operator ${operator} ${url}" >&2
  fetch_ipv4_prefixes "${url}" "${OPERATOR_FILE}"
done

for raw_asn in ${EXCLUDED_ASNS}; do
  url="${ASN_BASE_URL%/}/${raw_asn#AS}/ipv4-aggregated.txt"
  echo "[home-broadband] exclude ${raw_asn} ${url}" >&2
  fetch_ipv4_prefixes "${url}" "${EXCLUDED_FILE}"
done

merge_args=(--base "${RAW_FILE}" --extra "${OPERATOR_FILE}" --exclude "${EXCLUDED_FILE}")
if [[ "${CN_ALLOW_SHRINK:-0}" != "1" && -s "${OUTPUT}" ]]; then
  merge_args+=(--previous "${OUTPUT}")
fi
python3 "${MERGE_TOOL}" "${merge_args[@]}" > "${SORTED_FILE}"

mkdir -p "$(dirname "${OUTPUT}")"
{
  echo "# Generated by tools/prepare_home_broadband_data.sh"
  echo "# ASN-level approximation; see home-broadband-asns.tsv for scope and limitations."
  echo "# Sources: curated ASNs in home-broadband-asns.tsv + china-operator-ip (${OPERATOR_LISTS}) minus ${EXCLUDED_ASNS}."
  cat "${SORTED_FILE}"
} > "${OUTPUT}.tmp"
mv "${OUTPUT}.tmp" "${OUTPUT}"
echo "Wrote ${OUTPUT} ($(wc -l < "${SORTED_FILE}" | tr -d ' ') prefixes)" >&2
